/**
 * 서버로 나가기 전 구절에서 개인 식별 가능성이 있는 표현을 가린다.
 * 규칙 기반이라 완벽하지 않다. 학생 이름은 서술 본문에 거의 나오지 않는다는 가정이며,
 * 가려지지 않은 이름이 있을 수 있다는 점은 개인정보 안내·QA에서 다룬다.
 */
export function maskPersonalInfo(text: string): string {
  return text
    .replace(/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/gu, '[이메일]')
    .replace(/\d{2,4}[-\s]?\d{3,4}[-\s]?\d{4}/gu, '[번호]')
    .replace(/\d{6,}/gu, '[번호]')
    .replace(/[가-힣A-Za-z0-9]{2,}(?:초등학교|중학교|고등학교|대학교)/gu, '[학교]')
    .replace(/[가-힣]{2,4}\s*(?:선생님|교사|담임|교수)/gu, '[교사]')
    .replace(/[○◯]{2,}/gu, '[이름]');
}
